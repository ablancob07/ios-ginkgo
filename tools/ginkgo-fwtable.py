#!/usr/bin/env python3
"""Generate the modem firmware tables of TopazModem.cpp from a FAT image of the phone's
stock `modem` partition (NON-HLOS.bin).

  ginkgo-fwtable.py MODEM.img OUT.inc

The kernel reads firmware files straight from the partition (sweet_ufs_read_part), so it needs
to know where each file lies in the FAT volume:
  - fw_files[]: the MPSS images (image/modem.mdt, image/modem.bNN), offset + size + CRC32
    (each must be one contiguous run of clusters);
  - fw_ext[] + fw_all[]: every file (tftp service for /readonly/firmware/image/...), as a list
    of extents.
Only metadata is emitted (names, offsets, sizes, CRCs), never firmware content.
"""
import struct
import sys
import zlib


def main():
    img = open(sys.argv[1], 'rb').read()
    out = sys.argv[2]
    bps, spc, rsvd, nfats, rootents, tot16 = struct.unpack_from('<HBHBHH', img, 11)
    spf16 = struct.unpack_from('<H', img, 22)[0]
    tot32 = struct.unpack_from('<I', img, 32)[0]
    spf32, = struct.unpack_from('<I', img, 36)
    spf = spf16 or spf32
    total = tot16 or tot32
    root_sectors = (rootents * 32 + bps - 1) // bps
    first_data = rsvd + nfats * spf + root_sectors
    clusters = (total - first_data) // spc
    fat32 = clusters >= 65525
    fat16 = not fat32 and clusters >= 4085
    if not (fat16 or fat32):
        sys.exit('FAT12 not supported')
    csize = bps * spc
    fat_off = rsvd * bps

    def next_cluster(c):
        if fat32:
            return struct.unpack_from('<I', img, fat_off + 4 * c)[0] & 0x0fffffff
        return struct.unpack_from('<H', img, fat_off + 2 * c)[0]

    eoc = 0x0ffffff8 if fat32 else 0xfff8

    def chain(c):
        seen = 0
        while 2 <= c < eoc:
            yield c
            c = next_cluster(c)
            seen += 1
            if seen > clusters:
                raise SystemExit('FAT loop')

    def coff(c):
        return (first_data + (c - 2) * spc) * bps

    def dir_bytes(first):
        if first == 0 and not fat32:
            start = (rsvd + nfats * spf) * bps
            return img[start:start + root_sectors * bps]
        return b''.join(img[coff(c):coff(c) + csize] for c in chain(first))

    files = []   # (path, size, [(off, len)])

    def walk(first, prefix):
        data = dir_bytes(first)
        lfn = {}
        for i in range(0, len(data), 32):
            e = data[i:i + 32]
            if e[0] == 0:
                break
            if e[0] == 0xe5:
                lfn = {}
                continue
            attr = e[11]
            if attr == 0x0f:
                seq = e[0] & 0x1f
                part = e[1:11] + e[14:26] + e[28:32]
                lfn[seq] = part.decode('utf-16-le', 'ignore').split('\x00')[0].replace('￿', '')
                continue
            if attr & 0x08:
                lfn = {}
                continue
            if lfn:
                name = ''.join(lfn[k] for k in sorted(lfn))
            else:
                base = e[0:8].decode('ascii', 'replace').rstrip()
                ext = e[8:11].decode('ascii', 'replace').rstrip()
                name = (base + ('.' + ext if ext else ''))
                if e[12] & 0x08:
                    name = name.lower()
            lfn = {}
            if name in ('.', '..'):
                continue
            cl = struct.unpack_from('<H', e, 26)[0] | (struct.unpack_from('<H', e, 20)[0] << 16 if fat32 else 0)
            size = struct.unpack_from('<I', e, 28)[0]
            path = prefix + name
            if attr & 0x10:
                walk(cl, path + '/')
                continue
            ext_list = []
            left = size
            for c in chain(cl):
                if left <= 0:
                    break
                take = min(csize, left)
                o = coff(c)
                if ext_list and ext_list[-1][0] + ext_list[-1][1] == o:
                    ext_list[-1][1] += take
                else:
                    ext_list.append([o, take])
                left -= take
            files.append((path, size, ext_list))

    walk(struct.unpack_from('<I', img, 44)[0] if fat32 else 0, '')
    files.sort(key=lambda f: f[0].lower())

    lines = []
    nex = sum(len(f[2]) for f in files)
    lines.append('/* generated by tools/ginkgo-fwtable.py from the ginkgo modem partition: '
                 '%d files, %d extents, FAT%d */' % (len(files), nex, 32 if fat32 else 16))
    lines.append('static const struct { uint32_t off, len; } fw_ext[] = {')
    for _, _, ex in files:
        for o, l in ex:
            lines.append('\t{ %#x, %#x },' % (o, l))
    lines.append('};')
    lines.append('static const struct { const char *path; uint32_t size; uint16_t ext, next; } fw_all[] = {')
    idx = 0
    for p, s, ex in files:
        lines.append('\t{ "%s", %#x, %d, %d },' % (p, s, idx, len(ex)))
        idx += len(ex)
    lines.append('};')
    # MPSS images
    lines.append('/* MPSS images: offset, size, CRC32 (each one contiguous run) */')
    lines.append('static const struct { const char *name; uint32_t off, size, crc; } fw_files[] = {')
    for p, s, ex in files:
        n = p.split('/')[-1]
        if not (p.lower().startswith('image/modem.') and (n.lower().endswith('.mdt') or n.lower()[-4:-2] == '.b')):
            continue
        if len(ex) != 1:
            sys.exit('%s is fragmented (%d extents)' % (p, len(ex)))
        o = ex[0][0]
        crc = zlib.crc32(img[o:o + s]) & 0xffffffff
        lines.append('\t{ "%s", %#x, %#x, %#010x },' % (n.lower(), o, s, crc))
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('%s: %d files, %d extents, FAT%d, cluster %d bytes' % (out, len(files), nex, 32 if fat32 else 16, csize),
          file=sys.stderr)
    for p, s, ex in files:
        if p.lower().endswith(('modem.mdt', 'wlanmdsp.mbn')):
            print('  %s size %#x extents %d' % (p, s, len(ex)), file=sys.stderr)


if __name__ == '__main__':
    main()
